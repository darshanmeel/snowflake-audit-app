def coerce(value, typ: str):
    """A generator value as the column's type: generators were written against the docs' types."""
    if value is None:
        return None
    if typ == "JSON":
        if isinstance(value, str):
            try:
                json.loads(value)
                return value
            except ValueError:
                pass
        return json.dumps(value)
    if typ == "VARCHAR" and not isinstance(value, str):
        if isinstance(value, bool):
            return "true" if value else "false"
        return json.dumps(value) if isinstance(value, (list, dict)) else str(value)
    if typ in ("BIGINT", "DOUBLE") and isinstance(value, str):
        num = float(value)
        return int(num) if typ == "BIGINT" else num
    if typ == "BIGINT" and isinstance(value, float):
        return int(value)
    if typ == "BOOLEAN" and isinstance(value, str):
        return value.strip().upper() in ("TRUE", "YES", "Y", "1")
    return value


def create_all(con) -> None:
    """ATTACH an in-memory `snowflake` database and create every view and SHOW table empty."""
    con.execute(f"ATTACH ':memory:' AS {SNOWFLAKE_DB}")
    for schema, views in VIEWS.items():
        con.execute(f"CREATE SCHEMA {SNOWFLAKE_DB}.{schema}")
        for name, cols in views.items():
            ddl = ", ".join(f'"{c}" {t}' for c, t in cols)
            con.execute(f"CREATE TABLE {SNOWFLAKE_DB}.{schema}.{name} ({ddl})")
    con.execute(f"CREATE SCHEMA {SNOWFLAKE_DB}.{SHOW_SCHEMA}")
    for name, cols in SHOW_TABLES.items():
        ddl = ", ".join(f'"{c}" {t}' for c, t in cols)
        con.execute(f"CREATE TABLE {SNOWFLAKE_DB}.{SHOW_SCHEMA}.{name} ({ddl})")


