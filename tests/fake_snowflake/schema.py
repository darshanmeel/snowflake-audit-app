_TYPES = {"s": "VARCHAR", "n": "BIGINT", "f": "DOUBLE", "t": "TIMESTAMP", "d": "DATE",
          "b": "BOOLEAN", "j": "JSON"}


def _cols(spec: str) -> list[tuple[str, str]]:
    out = []
    for part in spec.split():
        name, code = part.split(":")
        out.append((name, _TYPES[code]))
    return out


