def _live_type(t: str) -> str:
    """A Snowflake type as the DuckDB type the fake uses."""
    m = re.fullmatch(r"NUMBER\((\d+),(\d+)\)", t)
    if m:
        return "BIGINT" if m.group(2) == "0" else "DOUBLE"
    if t.startswith("TIMESTAMP"):
        return "TIMESTAMP"
    return {"TEXT": "VARCHAR", "VARCHAR": "VARCHAR", "BINARY": "VARCHAR", "FLOAT": "DOUBLE",
            "DATE": "DATE", "BOOLEAN": "BOOLEAN", "VARIANT": "JSON", "OBJECT": "JSON",
            "ARRAY": "JSON"}[t]


def _live_cols(spec: str) -> list[tuple[str, str]]:
    return [(c, _live_type(t)) for c, t in (p.split(":", 1) for p in spec.split())]


