"""app/core/registry.py

Turns the check headers (app/queries/manifest.json, generated by tools/build_manifest.py from the
headers of app/queries/checks/*.sql) into typed QuerySpec objects. This is the single place that
parses a manifest entry and its .sql file into a structured record; the API and the export both
import this module instead of re-deriving any of it.

    load_registry() -> list[QuerySpec]   one entry per check
    by_id(query_id) -> QuerySpec         lookup, raises KeyError if not found

Every `reads` entry is validated at load time against SOURCE_CONTRACT (the Snowflake views, SHOW
commands and functions the checks read), and every `next` token against the set of query ids. A
validation failure raises RegistryError: fail loudly, never a silent skip.

app/core is imported by the app itself, so this module does NOT import anything from tools/; the
small amount of header parsing it needs (just enough to recover `caveats` and
`not_assessed_reasons`, the two header fields manifest.json does not carry) is reimplemented here.
"""
