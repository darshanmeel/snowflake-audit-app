class RegistryError(ValueError):
    """A structural problem in the check set (a `reads` entry outside SOURCE_CONTRACT, an
    unresolved `next` token). Raised at load time, never swallowed."""


# Header field names, mirroring tools/header_schema.py FIELDS + OPTIONAL_FIELDS by value (not by
# import, see the module docstring). Used to re-locate `caveats:` and `not_assessed_reasons:`.
_HEADER_FIELD_NAMES = (
    "query_id", "title", "domain", "reads", "requires", "params", "confidence",
    "confidence_note", "read_this", "healthy", "investigate_if", "actions", "next", "caveats",
    "runnable", "empty_if", "not_assessed_reasons", "windowed", "pre", "money", "entity",
)
_FIELD_RE = re.compile(r"^--\s*(" + "|".join(_HEADER_FIELD_NAMES) + r")\s*:\s?(.*)$")
# "code: words; code2: words2", the same shape as tools/header_schema.py's _REASON_RE.
_REASON_RE = re.compile(r"^([a-z][a-z0-9_]*)\s*:\s*(.+)$", re.I)


def _raw_header_fields(text: str) -> dict[str, str]:
    """The leading `--` header block of a .sql file as {field: value}; a `--` line that is not a
    known field start continues the field in progress (same rule as tools/header_schema.py)."""
    fields: dict[str, str] = {}
    current: str | None = None
    for line in text.splitlines():
        if not line.startswith("--"):
            break
        m = _FIELD_RE.match(line)
        if m:
            current = m.group(1)
            fields[current] = m.group(2).strip()
        else:
            cont = line[2:].strip()
            if current is not None and cont:
                fields[current] = (fields[current] + " " + cont).strip()
    return fields


def _parse_not_assessed_reasons(value: str) -> dict:
    """{code: words} from the `not_assessed_reasons:` value; {} when absent. A malformed entry is
    dropped here (tools/lint_headers.py is where a typo fails loudly), so one bad entry never
    turns into a 500 for every reader."""
    out: dict[str, str] = {}
    if not value or value.strip().lower().startswith("n/a"):
        return out
    for chunk in value.split(";"):
        m = _REASON_RE.match(chunk.strip())
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def _strip_header(text: str) -> str:
    """The query body: the .sql text without its leading `--` header block, trailing `;` removed."""
    lines = text.splitlines()
    i = 0
    while i < len(lines) and lines[i].startswith("--"):
        i += 1
    body = "\n".join(lines[i:]).strip()
    if body.endswith(";"):
        body = body[:-1].rstrip()
    return body


_VIEW_RE = re.compile(r"SNOWFLAKE\.([A-Z_]+)\.([A-Z][A-Z0-9_]*)")
_FUNCTION_RE = re.compile(r"([A-Z][A-Z0-9_$.]*)\(\)")


def parse_source(read: str) -> tuple[str, str]:
    """One `reads` entry -> (schema, name): SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY ->
    ("ACCOUNT_USAGE", "QUERY_HISTORY"); SHOW WAREHOUSES -> ("SHOW", "WAREHOUSES");
    SYSTEM$CLIENT_VERSION_INFO() -> ("FUNCTION", "SYSTEM$CLIENT_VERSION_INFO"). A pair outside
    SOURCE_CONTRACT raises RegistryError."""
    entry = read.strip().upper()
    if entry.startswith("SHOW "):
        name = re.sub(r"\s+LIKE\s+'[^']*'", "", entry[5:])
        name = re.sub(r"\s+(?:IN|ON)\s+ACCOUNT$", "", name).strip()
        pair = ("SHOW", name)
    elif m := _VIEW_RE.fullmatch(entry):
        pair = (m.group(1), m.group(2))
    elif m := _FUNCTION_RE.fullmatch(entry):
        pair = ("FUNCTION", m.group(1))
    else:
        raise RegistryError(
            f"reads entry {read!r} is not SNOWFLAKE.<schema>.<VIEW>, SHOW <object> or FUNCTION()"
        )
    if pair[1] not in SOURCE_CONTRACT.get(pair[0], set()):
        raise RegistryError(f"reads entry {read!r} ({pair[0]}, {pair[1]}) is not in SOURCE_CONTRACT")
    return pair


def _parse_sources(query_id: str, reads: list[str]) -> list[tuple[str, str]]:
    if not reads:
        raise RegistryError(f"{query_id}: reads is empty")
    try:
        return [parse_source(r) for r in reads]
    except RegistryError as e:
        raise RegistryError(f"{query_id}: {e}") from None


# is_finding is true only when `healthy` does not start with "n/a -" AND the body emits an
# "... AS status" column.
_STATUS_COL_RE = re.compile(r"AS\s+status\b", re.IGNORECASE)


@dataclass(frozen=True)
class QuerySpec:
    query_id: str
    title: str
    domain: str
    tier: str
    stars: bool            # no first-audit picks are defined yet: always False
    runnable: bool
    empty_if: list
    reads: list
    requires: str
    params: list           # [{name, default, meaning}], defaults already int/float where numeric
    confidence: str
    confidence_note: str
    read_this: str
    healthy: str
    investigate_if: str
    actions: list
    next: list
    sql_url: str
    learn_url: str          # docs.snowflake.com page of the first read (config/snowflake_docs.yml)
    origin: str            # always "checks" (one flat folder)
    path: str               # repo-relative .sql path, e.g. app/queries/checks/cost_daily_spikes.sql
    sources: list            # list[tuple[schema, name]], one per `reads` entry
    executable: bool         # the header does not say `runnable: false`
    is_finding: bool
    windowed: bool           # header `windowed: yes`: the period_days selector drives the query
    pre: list                # `pre:` SHOW statements, run first on the same cursor, in order
    body: str                # header-stripped query text, trailing ';' removed
    caveats: str              # parsed straight from the .sql file (manifest.json lacks it)
    not_assessed_reasons: dict   # {code: words} for the query's own not_assessed_reason column
    money: str | None = None     # the output column that is the check's headline money figure
    entity: dict | None = None   # {"noun", "columns"}: what one row is an instance of

    def param_defaults(self) -> dict:
        """{name: default} for every declared param (period_days included when windowed)."""
        return {p["name"]: p["default"] for p in self.params}


def _load_manifest() -> list[QuerySpec]:
    if not MANIFEST_PATH.exists():
        return []
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    try:
        docs = snowflake_docs.load_docs()
    except (snowflake_docs.DocsError, OSError):
        docs = {}  # a broken docs file costs the links, not the checks; the Guide reports it
    specs: list[QuerySpec] = []
    for entries in manifest.values():
        for entry in entries:
            qid = entry["query_id"]
            sql_path = CHECKS_DIR / f"{qid}.sql"
            text = sql_path.read_text(encoding="utf-8")
            body = _strip_header(text)
            raw = _raw_header_fields(text)
            reads = entry["reads"]
            sources = _parse_sources(qid, reads)
            first = docs.get(f"{sources[0][0]}.{sources[0][1]}")
            is_finding = (
                not entry["healthy"].strip().lower().startswith("n/a -")
                and bool(_STATUS_COL_RE.search(body))
            )
            specs.append(
                QuerySpec(
                    query_id=qid,
                    title=entry["title"],
                    domain=entry["domain"],
                    tier=entry["tier"],
                    stars=False,
                    runnable=entry["runnable"],
                    empty_if=entry["empty_if"],
                    reads=reads,
                    requires=entry["requires"],
                    params=entry["params"],
                    confidence=entry["confidence"],
                    confidence_note=entry["confidence_note"],
                    read_this=entry["read_this"],
                    healthy=entry["healthy"],
                    investigate_if=entry["investigate_if"],
                    actions=entry["actions"],
                    next=entry["next"],
                    sql_url=entry["sql_url"],
                    learn_url=first.url if first else "",
                    origin="checks",
                    path=sql_path.relative_to(ROOT).as_posix(),
                    sources=sources,
                    executable=bool(entry["runnable"]),
                    is_finding=is_finding,
                    windowed=bool(entry["windowed"]),
                    pre=list(entry["pre"]),
                    body=body,
                    caveats=raw.get("caveats", ""),
                    not_assessed_reasons=_parse_not_assessed_reasons(raw.get("not_assessed_reasons", "")),
                    money=entry.get("money"),
                    entity=entry.get("entity"),
                )
            )
    return specs


def _validate_next(specs: list[QuerySpec]) -> None:
    ids = {s.query_id for s in specs}
    for s in specs:
        for n in s.next:
            if n["query_id"] not in ids:
                raise RegistryError(
                    f"{s.query_id}: next-entry target '{n['query_id']}' is not a check in the registry"
                )


# Parsing the manifest plus every .sql header takes a moment and pages call by_id() once per query,
# so the result is cached against the manifest's and docs file's (mtime_ns, size). QuerySpec is
# frozen, so callers cannot corrupt the cache.
_CACHE: tuple[tuple, list[QuerySpec]] | None = None


def _cache_key() -> tuple:
    key = []
    for p in (MANIFEST_PATH, snowflake_docs._PATH):
        try:
            st = p.stat()
            key.append((str(p), st.st_mtime_ns, st.st_size))
        except OSError:
            key.append((str(p), None, None))
    return tuple(key)


def load_registry() -> list[QuerySpec]:
    """Every check in app/queries/manifest.json. Cached (see _CACHE); the returned list is a
    fresh copy, so a caller that sorts or filters in place cannot affect the cache."""
    global _CACHE
    key = _cache_key()
    if _CACHE is not None and _CACHE[0] == key:
        return list(_CACHE[1])
    specs = _load_manifest()
    _validate_next(specs)
    _CACHE = (key, specs)
    return list(specs)


def by_id(query_id: str) -> QuerySpec:
    for s in load_registry():
        if s.query_id == query_id:
            return s
    raise KeyError(query_id)
